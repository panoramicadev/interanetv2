-- 095: Solicitud de Muestra (oct-2026).
--
-- El vendedor pide una muestra (producto, color o material de exhibición) para
-- un cliente existente. El supervisor la aprueba o la rechaza; aprobada queda en
-- curso, Administración crea la NVV y la cierra cuando se entregó. Mensajes y
-- cambios de estado van a solicitud_muestra_mensajes.
--
-- Lo mismo lo crea ensureSolicitudesMuestraTablas (server/migrations.ts) al arrancar.

CREATE TABLE IF NOT EXISTS solicitudes_muestra (
  id VARCHAR PRIMARY KEY DEFAULT gen_random_uuid(),
  numero INTEGER GENERATED BY DEFAULT AS IDENTITY,
  tipo VARCHAR(20) NOT NULL,
  estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
  cliente_id VARCHAR NOT NULL,
  cliente_nombre TEXT NOT NULL,
  cliente_rut VARCHAR(20),
  obra TEXT,
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  motivo TEXT,
  solicitante_id VARCHAR,
  solicitante_nombre TEXT,
  supervisor_id VARCHAR,
  aprobada_por_id VARCHAR,
  aprobada_por_nombre TEXT,
  aprobada_at TIMESTAMPTZ,
  motivo_rechazo TEXT,
  nvv_numero VARCHAR(40),
  nvv_registrada_por_nombre TEXT,
  nvv_registrada_at TIMESTAMPTZ,
  cerrada_por_id VARCHAR,
  cerrada_por_nombre TEXT,
  cerrada_at TIMESTAMPTZ,
  ultimo_movimiento_at TIMESTAMPTZ DEFAULT now(),
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "IDX_solicitudes_muestra_solicitante" ON solicitudes_muestra (solicitante_id);
CREATE INDEX IF NOT EXISTS "IDX_solicitudes_muestra_supervisor" ON solicitudes_muestra (supervisor_id);
CREATE INDEX IF NOT EXISTS "IDX_solicitudes_muestra_estado" ON solicitudes_muestra (estado);

CREATE TABLE IF NOT EXISTS solicitud_muestra_mensajes (
  id VARCHAR PRIMARY KEY DEFAULT gen_random_uuid(),
  solicitud_id VARCHAR NOT NULL REFERENCES solicitudes_muestra(id) ON DELETE CASCADE,
  autor_id VARCHAR,
  autor_nombre TEXT,
  autor_rol VARCHAR(40),
  texto TEXT,
  adjunto_url TEXT,
  adjunto_nombre TEXT,
  evento VARCHAR(30),
  created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "IDX_solicitud_muestra_mensajes_solicitud" ON solicitud_muestra_mensajes (solicitud_id);
